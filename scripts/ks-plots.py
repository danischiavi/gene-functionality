import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt
import numpy as np
from pandas.plotting import parallel_coordinates
from datetime import datetime
date = datetime.now().strftime('%Y%m%d')

# Set the color palette for the groups
custom_palette = {
	'Random':'grey',		
	'Intrinsic':'goldenrod',	 
	'Conservation':'orangered',  
	'Transcription':'forestgreen',				
	'Epigenetic':'deepskyblue',		
	'Coding/Structure':'royalblue',	  
	'Repeats':'darkorange',	   
	'Population':'hotpink'	 
}

feature_to_group = {
	'Tissue RPKM': 'Transcription',
	'Primary cell RPKM': 'Transcription',
	'PhyloP-mammals': 'Conservation',
	'PhyloP-vertebrates': 'Conservation',
	'GERP-mammals': 'Conservation',
	'H3K79me2': 'Epigenetic',
	'H3K79me1': 'Epigenetic',
	'Copies': 'Repeats',
	'MaxEnt splicing': 'Coding/Structure', 
	'RNAcode': 'Coding/Structure',
	'GERP-vertebrates': 'Conservation',
	'Covariance': 'Coding/Structure',
	'H3K9ac': 'Epigenetic',
	'Chromatin acc': 'Epigenetic',
	'GC%': 'Intrinsic',
	'CpG': 'Intrinsic',
	'TA': 'Intrinsic',
	'AC': 'Intrinsic',
	'CC': 'Intrinsic',
	'GA': 'Intrinsic',
	'T%': 'Intrinsic',
	'G%': 'Intrinsic',
	'C%': 'Intrinsic',
	'MFE': 'Coding/Structure',
	'Interactions': 'Coding/Structure',
	'Methylome': 'Epigenetic',
	'Repeat free': 'Repeats',
	'Fickett': 'Coding/Structure',
	'GG': 'Intrinsic',
	'Low complexity': 'Intrinsic',
	'GT': 'Intrinsic',
	'SNPs': 'Population',
	'MAF': 'Population',
	'Random': 'Random'
}

rna_types = ['mrna', 'sncrna', 'lncrna', 'allrna']

for rna in rna_types:
	df = pd.read_csv(f"./results/20251207-ks_statistics_{rna}.csv")
	df = df.sort_values(by='ks', ascending=False)
	df['Group'] = df['feature'].map(feature_to_group)
	# Get the explicit order of features after sorting, to ensure seaborn uses this exact order
	feature_order = df['feature'].tolist()
	# Create the plot
	plt.figure(figsize=(8, 10))
	# Pass the 'order' parameter to sns.barplot to control the y-axis category order
	ax = sns.barplot(x='ks', y='feature', data=df, hue='Group', dodge=False, palette=custom_palette, order=feature_order, legend=False)
	# Add error bars
	# Iterate through the features in the defined order to correctly align error bars
	for i, feature_name in enumerate(feature_order):
		# Find the corresponding row in the DataFrame for the current feature
		row = df[df['feature'] == feature_name].iloc[0]
		bar_x = row['ks']
		# Calculate the absolute difference for lower and upper errors
		lower = abs(row['ks'] - row['ks_lower'])
		upper = abs(row['ks_upper'] - row['ks'])
		# The y-position for the i-th feature in the ordered list is simply its numerical index 'i'
		# on the categorical y-axis generated by seaborn.
		center_y = i
		plt.errorbar(
			x=np.array([bar_x]),
			y=np.array([center_y]),
			xerr=np.array([[lower], [upper]]),
			fmt='none', # 'none' means no connecting line/marker
			capsize=3,  # Size of the error bar caps
			color='black',
			linewidth=1.5
		)
	plt.xlim(0, 0.9) 
	# Set plot labels and title
	plt.yticks(fontsize=19)
	plt.xticks(fontsize=18)
	plt.xlabel('KS-statistic', fontsize=20)
	plt.title(rna.replace("rna", "RNA"), fontsize=30)
	#plt.legend(title='Feature group', bbox_to_anchor=(1.05, 1), loc='upper left', fontsize=18)
	plt.tight_layout()
	plt.savefig(f"./results/plots/feature_comparison_{rna}_{date}.png", dpi=600, bbox_inches='tight')





