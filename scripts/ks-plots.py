file_path = './results/20251206-ks-for-plot.csv'  
df = pd.read_csv(file_path)

#df = df.drop(columns=['all', 'all_upper', 'all_lower']) # Added manually afterwards as a horizontal line 

# Melt the DataFrame to long format for KS-statistic values
df_melted = pd.melt(df, id_vars=['feature'], 
					value_vars=['mRNA', 'sncRNA', 'lncRNA'], 
					var_name='Dataset', value_name='KS-statistic')

# Melt for upper confidence intervals
df_upper = pd.melt(df, id_vars=['feature'], 
				   value_vars=['mRNA_upper', 'sncRNA_upper', 'lncRNA_upper'], 
				   var_name='Dataset', value_name='KS-statistic_upper')

# Melt for lower confidence intervals
df_lower = pd.melt(df, id_vars=['feature'], 
				   value_vars=['mRNA_lower', 'sncRNA_lower', 'lncRNA_lower'], 
				   var_name='Dataset', value_name='KS-statistic_lower')

# Remove '_upper' and '_lower' from Dataset names for merging
df_upper['Dataset'] = df_upper['Dataset'].str.replace('_upper', '')
df_lower['Dataset'] = df_lower['Dataset'].str.replace('_lower', '')

# Merge upper and lower confidence intervals with the main DataFrame
df_melted = df_melted.merge(df_upper, on=['feature', 'Dataset'], how='left')
df_melted = df_melted.merge(df_lower, on=['feature', 'Dataset'], how='left')

df_melted['feature'] = pd.Categorical(df_melted['feature'], categories=features, ordered=True) 
df_melted = df_melted.sort_values('feature')

# Create scatter plot
plt.figure(figsize=(16, 8))
ax = sns.scatterplot(data=df_melted, x='feature', y='KS-statistic', hue='Dataset', style='Dataset', s=200, legend=True)

for i in range(len(df_melted)):
	lower = abs(df_melted['KS-statistic'][i] - df_melted['KS-statistic_lower'][i])
	upper = abs(df_melted['KS-statistic_upper'][i] - df_melted['KS-statistic'][i])
	
	plt.errorbar(
		x=df_melted['feature'][i],
		y=df_melted['KS-statistic'][i],
		yerr=[[lower], [upper]],  # nested list for asymmetric error bars
		fmt='none',
		capsize=4,
		color='black',
		linewidth=1.5,
		alpha=0.8
	)

ax.axhline(y=0.02, color='red', linestyle='--', linewidth=1)  # Customize color, linestyle, and linewidth

ax.yaxis.grid(True, linestyle='--', linewidth=0.5, color='gray', alpha=0.7)  # Horizontal grid lines
ax.xaxis.grid(True, linestyle='--', linewidth=0.5, color='gray', alpha=0.7) 
ticks = ax.get_xticks()
ax.set_xticks(ticks + 0.1)   # shift right by 0.1 units
# Rotate x-axis labels for better readability
plt.xticks(rotation=45, fontsize=20, ha='right', rotation_mode='anchor')
plt.yticks(fontsize=20)
plt.xlabel('Feature', fontsize=20)
plt.ylabel('KS-statistic', fontsize=20)
plt.legend(fontsize=20)
